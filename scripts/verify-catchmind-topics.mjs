// Two independent browser sessions against online-fixture.mjs; refreshes are explicit, not Realtime.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { launchChromium } from './playwright-browser.mjs';
const base = process.env.CATCHMIND_QA_URL || 'http://127.0.0.1:5212';
const out = path.resolve(process.env.PLAYWRIGHT_ARTIFACT_DIR || 'output/playwright/catchmind-topics');
await fs.mkdir(out, { recursive: true });
const browser = await launchChromium();
const contexts = await Promise.all([browser.newContext({ viewport: { width: 1440, height: 900 } }), browser.newContext({ viewport: { width: 1440, height: 900 } })]);
const pages = await Promise.all(contexts.map(context => context.newPage()));
const errors = []; pages.forEach(page => page.on('pageerror', error => errors.push(error.message)));
const reports = [];
const refresh = async () => { for (const page of pages) await page.evaluate(() => window.qaClient.reconnectRoom()); };
const snapshot = page => page.evaluate(() => window.qaClient.getSnapshot());
try {
  for (const page of pages) {
    await page.goto(`${base}/play`);
    await page.locator('#nickname').waitFor();
    await page.evaluate(async () => { window.qaClient = (await import('/src/core/client.ts')).client; window.qaNavigate = (await import('/src/app/Router.tsx')).navigate; });
  }
  const id = await pages[0].evaluate(() => window.qaClient.createRoom('QA KO', 'ko'));
  await pages[1].evaluate(id => window.qaClient.joinRoom(id, 'QA ES', 'es'), id);
  for (const page of pages) await page.evaluate(id => window.qaNavigate(`/room/${id}`), id);
  await pages[0].evaluate(() => window.qaClient.selectGame('catchmind')); await refresh();
  await pages[1].evaluate(() => window.qaClient.selectGame('catchmind')); await refresh();
  await pages[0].locator('.cm-table').waitFor();
  assert.equal(await pages[0].locator('.cm-categories input[type=radio]').count(), 6);
  assert.equal(await pages[1].locator('.cm-categories').count(), 0);
  assert.equal((await snapshot(pages[0])).view.hand.choices.length, 0);
  await pages[0].screenshot({ path: path.join(out, '01-host-category-desktop.png'), fullPage: true });
  await pages[0].locator('input[value=food]').check();
  await pages[0].locator('.cm-setting-grid input[type=number]').nth(0).fill('30');
  await pages[0].locator('.cm-setting-grid input[type=number]').nth(1).fill('2');
  await pages[0].locator('.cm-settings-foot button').click(); await refresh();
  assert.equal((await snapshot(pages[0])).view.board.settings.category_id, 'food');
  const options = (await snapshot(pages[0])).view.hand.choices;
  const dictionary = await pages[0].evaluate(async () => (await import('/src/games/catchmindTopics.ts')).catchmindTopicWords);
  assert(options.every(word => dictionary.some(entry => entry.category_id === 'food' && entry.ko === word.ko && entry.es === word.es)));
  await pages[0].locator('.cm-word-choices button').first().click(); await refresh();
  const drawing = await snapshot(pages[0]), guessing = await snapshot(pages[1]);
  assert.equal(drawing.playerId, 'p1'); assert.equal(guessing.playerId, 'p2');
  assert.equal(guessing.view.hand, null); assert.equal(guessing.view.board.answer, null);
  const answer = drawing.view.hand.answer;
  assert.equal(await pages[0].locator('.cm-categories').count(), 0);
  assert.equal(await pages[1].locator('.cm-hint-word').count(), 1);
  assert.equal(await pages[1].locator('.cm-hint-word').textContent(), `${guessing.view.board.hintWord.ko} / ${guessing.view.board.hintWord.es}`);
  assert(!(await pages[1].locator('.cm-table').textContent()).includes(answer.es));
  // Use real mouse input for a representative synchronized stroke.
  const box = await pages[0].locator('canvas').boundingBox();
  await pages[0].mouse.move(box.x + box.width * .25, box.y + box.height * .3); await pages[0].mouse.down();
  await pages[0].mouse.move(box.x + box.width * .65, box.y + box.height * .6, { steps: 15 }); await pages[0].mouse.up();
  await pages[0].waitForFunction(() => window.qaClient.getSnapshot().view.board.strokes.length > 0); await refresh();
  assert.equal((await snapshot(pages[0])).version, (await snapshot(pages[1])).version);
  await pages[0].screenshot({ path: path.join(out, '02-drawer-desktop.png'), fullPage: true });
  await pages[1].screenshot({ path: path.join(out, '03-guesser-static-mask-es.png'), fullPage: true });
  await pages[1].locator('#room-message').fill(answer.es); await pages[1].locator('#room-message').press('Enter');
  await pages[1].waitForFunction(() => window.qaClient.getSnapshot().view.phase === 'round-over'); await refresh();
  assert.equal((await snapshot(pages[0])).view.board.answer.ko, (await snapshot(pages[1])).view.board.answer.ko);
  await pages[0].getByRole('button', { name: /다음 라운드/ }).click(); await refresh();
  await pages[1].locator('.cm-word-choices button').first().click(); await refresh();
  const deadline = (await snapshot(pages[1])).view.deadlineAt;
  await pages[1].reload(); await pages[1].locator('.cm-table').waitFor();
  await pages[1].evaluate(async () => { window.qaClient = (await import('/src/core/client.ts')).client; }); await refresh();
  assert.equal((await snapshot(pages[1])).view.deadlineAt, deadline);
  await pages[1].getByRole('button', { name: /Pasar palabra/ }).click(); await refresh();
  await pages[1].getByRole('button', { name: /Siguiente ronda/ }).click(); await refresh();
  assert((await snapshot(pages[0])).view.result);
  await pages[0].screenshot({ path: path.join(out, '04-result-rematch-desktop.png'), fullPage: true });
  const oldVersion = (await snapshot(pages[0])).version;
  await pages[0].getByRole('button', { name: '다시 하기', exact: true }).click(); await refresh();
  assert((await snapshot(pages[0])).view.result); assert.equal((await snapshot(pages[0])).version, oldVersion + 1);
  await pages[1].getByRole('button', { name: 'Aceptar revancha', exact: true }).click(); await refresh();
  const reset = (await snapshot(pages[0])).view;
  assert.equal(reset.phase, 'choosing'); assert.equal(reset.deadlineAt, null); assert.equal(reset.board.settings.category_id, null);
  assert.deepEqual(reset.board.scores, { p1: 0, p2: 0 }); assert.deepEqual(reset.board.strokes, []); assert.deepEqual(reset.hand.choices, []);
  await pages[0].locator('input[value=nature_space]').check();
  await pages[0].locator('.cm-setting-grid input[type=number]').nth(0).fill('30');
  await pages[0].locator('.cm-settings-foot button').click(); await refresh();
  await pages[0].locator('.cm-word-choices button').first().click(); await refresh();
  const lateAnswer = (await snapshot(pages[0])).view.hand.answer.es;
  await Promise.race(pages.map(page => page.waitForFunction(() => window.qaClient.getSnapshot().view.phase === 'round-over', null, { timeout: 42000 }))); await refresh();
  const timed = await Promise.all(pages.map(snapshot));
  assert.equal(timed[0].version, timed[1].version);
  for (const current of timed) { assert.equal(current.view.phase, 'round-over'); assert.equal(current.view.deadlineAt, null); assert.deepEqual(current.view.board.scores, { p1: 0, p2: 0 }); }
  const expiredVersion = timed[1].version;
  await pages[1].locator('#room-message').fill(lateAnswer); await pages[1].locator('#room-message').press('Enter');
  await pages[1].waitForFunction(version => window.qaClient.getSnapshot().version > version, expiredVersion); await refresh();
  assert.notEqual((await snapshot(pages[1])).messages.at(-1)?.status, 'correct');
  assert.deepEqual((await snapshot(pages[1])).view.board.scores, { p1: 0, p2: 0 });
  await pages[1].screenshot({ path: path.join(out, '05-real-30-second-timeout-es.png'), fullPage: true });
  assert.deepEqual(errors, []);
  reports.push({ independentSessions: 2, viewport: '1440×900', categories: 6, selectedCategory: 'food', bilingualAnswer: true, privateAnswer: true, staticMasks: true, synchronizedStroke: true, reloadPreservesDeadline: true, rematchRequiresBoth: true, resetVerified: true, actualThirtySecondTimeout: true, lateAnswerRejected: true, realtimeVerified: false, productionDeployed: false });
  await fs.writeFile(path.join(out, 'report.json'), JSON.stringify({ reports, errors }, null, 2));
  console.log(JSON.stringify({ reports, errors }, null, 2));
} catch (error) {
  await pages[0].screenshot({ path: path.join(out, 'failed-state.png'), fullPage: true });
  console.error(JSON.stringify({ errors, states: await Promise.all(pages.map(async page => { const current = await snapshot(page).catch(() => ({})); return { game: current.gameId, version: current.version, phase: current.view?.phase, error: current.error }; })) }));
  throw error;
} finally { await browser.close(); }
