import { chromium } from 'file:///opt/codex/cua_node/lib/node_modules/playwright/index.mjs';
import fs from 'node:fs/promises';
import path from 'node:path';

const url = process.env.LANDING_URL || 'http://127.0.0.1:5191/';
const dir = path.resolve('output/playwright/landing-motion-upgrade');
const videoDir = path.join(dir, 'native-video');
await fs.mkdir(videoDir, { recursive: true });
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const timeline = [];
let pageErrors = [];
const mark = async name => timeline.push({ seconds: +(Date.now() / 1000 - started).toFixed(1), name });
const wait = async (ms, name) => { await page.waitForTimeout(ms); if (name) await mark(name); };
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: videoDir, size: { width: 1440, height: 900 } } });
await context.addInitScript(() => localStorage.setItem('dos-language', 'ko'));
const page = await context.newPage();
page.on('pageerror', error => pageErrors.push(error.message));
const started = Date.now() / 1000;
try {
  await page.goto(url, { waitUntil: 'domcontentloaded' });
  await page.locator('.landing').waitFor({ state: 'visible' });
  await page.evaluate(() => document.fonts.ready);
  await mark('Hero: full scene, CTA idle, particles and SVG orbit drawing');
  await wait(4200, 'Idle portrait, candle, star particles and orbit animation');
  const hero = page.locator('.hero-scene');
  const heroBox = await hero.boundingBox();
  if (heroBox) await page.mouse.move(heroBox.x + heroBox.width * .18, heroBox.y + heroBox.height * .33);
  await wait(2700, 'Parallax position A');
  if (heroBox) await page.mouse.move(heroBox.x + heroBox.width * .82, heroBox.y + heroBox.height * .66);
  await wait(2700, 'Parallax position B');
  await page.mouse.move(1435, 14);
  await wait(550, 'Parallax resets at scene edge');
  await page.locator('.hero-actions .primary-action').hover();
  await wait(3200, 'CTA hover glow over idle pulse');
  await page.locator('.hero-glass-heart').click();
  await wait(1300, 'Click heart to emit spark particles');
  const envelope = page.locator('.hero-envelope');
  await envelope.hover();
  await wait(2000, 'Envelope hover preview');
  await envelope.focus();
  await page.keyboard.press('Enter');
  await wait(1800, 'Envelope keyboard preview');
  await envelope.click();
  await wait(1800, 'Envelope click preview toggle');
  await page.locator('#games').scrollIntoViewIfNeeded();
  await wait(800, 'Scroll into game rail');
  const card = page.locator('.game-rail-card').first();
  const cardBox = await card.boundingBox();
  if (cardBox) await page.mouse.move(cardBox.x + cardBox.width * .77, cardBox.y + 28);
  await wait(3200, 'Card hover tilt, light sweep, expanded description');
  await card.click();
  await page.waitForURL(/\/play\?game=/, { timeout: 5000 });
  await wait(1200, 'Real card click navigates to game');
  await page.goBack();
  await page.locator('.moment-notes').waitFor({ state: 'attached' });
  await page.locator('.moment-notes').evaluate(el => el.scrollIntoView({ block: 'center' }));
  await wait(2400, 'Three how-to blocks and Catchmind translation fallback note');
  const fold = page.locator('#papi-letter .moment-fold-button');
  await fold.click();
  await wait(1200, 'Fold the long Papi letter');
  await fold.focus();
  await page.keyboard.press('Enter');
  await wait(1200, 'Keyboard reopens Papi letter');
  await page.locator('.moment-note a[href="/feedback"]').click();
  await page.locator('.feedback-setup, .feedback-compose').first().waitFor({ state: 'visible', timeout: 5000 });
  await wait(1800, 'Open Mami ideas feedback route');
  await page.goto(url, { waitUntil: 'domcontentloaded' });
  await page.locator('.landing').waitFor({ state: 'visible' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const reducedHero = page.locator('.hero-scene');
  const reducedBox = await reducedHero.boundingBox();
  if (reducedBox) await page.mouse.move(reducedBox.x + reducedBox.width * .8, reducedBox.y + reducedBox.height * .5);
  await wait(2700, 'Reduced motion: static scene and immediate conversation');
  await page.screenshot({ path: path.join(dir, 'landing-motion-upgrade-ko-final-motion.png'), fullPage: true });
  const video = page.video();
  await context.close();
  const webm = await video.path();
  await fs.copyFile(webm, path.join(videoDir, 'landing-motion-upgrade.webm'));
  await fs.writeFile(path.join(dir, 'landing-motion-upgrade-timeline.json'), JSON.stringify({ url, durationSeconds: +(Date.now() / 1000 - started).toFixed(1), timeline, pageErrors }, null, 2) + '\n');
  if (pageErrors.length) throw new Error(`page_errors:${pageErrors.join(';')}`);
} catch (error) {
  await browser.close();
  throw error;
}

const dragContext = await browser.newContext({ viewport: { width: 1024, height: 900 }, recordVideo: { dir: videoDir, size: { width: 1024, height: 900 } } });
await dragContext.addInitScript(() => localStorage.setItem('dos-language', 'ko'));
const dragPage = await dragContext.newPage();
await dragPage.goto(url, { waitUntil: 'domcontentloaded' });
await dragPage.locator('.game-rail-track').waitFor({ state: 'visible' });
const track = dragPage.locator('.game-rail-track');
const box = await track.boundingBox();
if (box) {
  await dragPage.mouse.move(box.x + box.width * .78, box.y + box.height / 2);
  await dragPage.mouse.down();
  await dragPage.mouse.move(box.x + box.width * .22, box.y + box.height / 2, { steps: 8 });
  await dragPage.mouse.up();
}
await dragPage.waitForTimeout(700);
const dragEvidence = await track.evaluate(el => ({ scrollLeft: el.scrollLeft, clientWidth: el.clientWidth, scrollWidth: el.scrollWidth, url: location.href }));
await dragPage.screenshot({ path: path.join(dir, 'landing-motion-upgrade-ko-drag.png'), fullPage: false });
const dragVideo = dragPage.video();
await dragContext.close();
const dragWebm = await dragVideo.path();
await fs.copyFile(dragWebm, path.join(videoDir, 'landing-motion-upgrade-drag.webm'));
await fs.writeFile(path.join(dir, 'landing-motion-upgrade-drag.json'), JSON.stringify(dragEvidence, null, 2) + '\n');
await browser.close();
console.log(JSON.stringify({ videoDir, timelinePath: path.join(dir, 'landing-motion-upgrade-timeline.json'), dragEvidence }));
